/**
 * Get jurisdiction by ID (case-insensitive).
 */
function getJurisdiction(id) {
  const key = Object.keys(JURISDICTIONS).find(
    k => JURISDICTIONS[k].id === id.toLowerCase().replace(/[\s-]/g, '_').replace('hong_kong', 'hong_kong')
  );
  return key ? JURISDICTIONS[key] : null;
}

/**
 * Get all jurisdictions as an array.
 */
function getAllJurisdictions() {
  return Object.values(JURISDICTIONS);
}

/**
 * Build a jurisdiction context block for injection into AI prompts.
 */
function buildJurisdictionPrompt(jurisdictionId) {
  const j = getJurisdiction(jurisdictionId);
  if (!j) return '';
  return `
[JURISDICTION: ${j.name} ${j.flag}]
Governing Law: ${j.governingLaw}
Courts & Arbitration: ${j.courts}
Regulators: ${j.regulators.join(', ')}
Key Features:
${j.keyFeatures.map(f => `  • ${f}`).join('\n')}
Fund Structures: ${j.fundStructures.join(', ')}
NDA Standards: ${j.ndaStandards}
LPA Standards: ${j.lpaStandards}
Disclaimer: ${j.disclaimer}
  `.trim();
}

